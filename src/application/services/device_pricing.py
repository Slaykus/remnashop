"""
Цена устройств сверх базовых двух.

До сих пор количество устройств было свойством тарифа: Solo два, Duo
четыре, и переход между ними стоил ровно вдвое. Рынок на это ответил —
за семь месяцев Duo купили 24 раза против 217 у Solo, а 39% владельцев
Solo при этом сидят на двух устройствах из двух. Люди упираются в
потолок и не покупают удвоение.

Поэтому цена считается по одной формуле, а тарифы становятся её
пресетами: сколько бы устройств человек ни набрал — докупая по одному
или взяв готовый тариф, — он платит одинаково. Двух дорог к одному
результату по разной цене больше нет.

Ставка убывает, но не свободно: пока устройств мало, она держится близко
к подушевой цене Solo. Иначе выгоднее будет скинуться вчетвером на один
тариф, чем купить четыре, и мы обменяем четыре оплаты на одну.
"""

from decimal import ROUND_HALF_UP, Decimal
from typing import Final

# Устройства, входящие в базовый тариф. Дешевле этого продавать нечего:
# Solo — минимальный план и якорь всего прайса.
BASE_DEVICES: Final[int] = 2

# Предельная ставка за устройство в месяц, по его порядковому номеру.
# Сравнение для понимания порядка цифр: в Solo устройство стоит 100 ₽.
#
# До шести ставка не падает вовсе — там живут семьи, и там же риск
# складчины: четыре устройства по 80 ₽ дают 360 ₽ против 400 ₽ за два
# Solo, то есть выгода 10%. Ради десяти процентов не договариваются.
#
# Ниже начинается скидка за объём, но добраться туда можно, только
# собрав десяток человек, а это уже организация, а не компания друзей.
_RATES: Final[tuple[tuple[int, Decimal], ...]] = (
    (6, Decimal(80)),    # устройства 3–6
    (10, Decimal(70)),   # 7–10
    (20, Decimal(60)),   # 11–20
    (10**6, Decimal(50)),  # 21 и дальше
)

# Во сколько обходится месяц при покупке сразу на несколько. Значения не
# придуманы заново: это ровно те множители, по которым в проекте уже
# посчитаны все тарифы (x1 / x2.7 / x4.8 / x8.4 к месячной цене).
_TERM_FACTORS: Final[dict[int, Decimal]] = {
    30: Decimal("1.0"),
    90: Decimal("0.9"),
    180: Decimal("0.8"),
    365: Decimal("0.6904"),
}

_DAYS_IN_MONTH: Final[Decimal] = Decimal(30)


def monthly_rate(device_index: int) -> Decimal:
    """Сколько стоит в месяц устройство с таким порядковым номером."""
    if device_index <= BASE_DEVICES:
        return Decimal(0)

    for upper_bound, rate in _RATES:
        if device_index <= upper_bound:
            return rate

    return _RATES[-1][1]


def monthly_extra_price(total_devices: int) -> Decimal:
    """Месячная доплата за всё, что сверх базовых двух устройств."""
    if total_devices <= BASE_DEVICES:
        return Decimal(0)

    return sum(
        (monthly_rate(index) for index in range(BASE_DEVICES + 1, total_devices + 1)),
        Decimal(0),
    )


def term_factor(term_days: int) -> Decimal:
    """
    Во сколько обходится месяц при сроке подписки в 'term_days'.

    Незнакомый срок считаем месячным: занижать скидку безопаснее, чем
    выдать её там, где мы её не назначали.
    """
    return _TERM_FACTORS.get(term_days, Decimal("1.0"))


def extra_devices_price(total_devices: int, term_days: int, days: int | None = None) -> Decimal:
    """
    Доплата за устройства сверх базовых, в рублях.

    'term_days' — срок подписки, он задаёт скидку за длительность.
    'days' — на сколько дней покупаем; по умолчанию на весь срок.

    Разделение нужно для докупки в середине оплаченного периода: человек
    платит только за оставшиеся дни, но по ставке своего срока. Иначе
    годовой подписчик доплачивал бы по месячной ставке и вышло бы дороже,
    чем если бы он взял то же устройство при продлении.
    """
    if days is None:
        days = term_days
    if days <= 0 or total_devices <= BASE_DEVICES:
        return Decimal(0)

    price = (
        monthly_extra_price(total_devices)
        * term_factor(term_days)
        * Decimal(days)
        / _DAYS_IN_MONTH
    )
    return price.quantize(Decimal("1"), rounding=ROUND_HALF_UP)
